import type { ProgramSection, ProgramTopic, TopicContentStatus, TopicKind } from "@/types/program";

function topic(
  id: string,
  title: string,
  hoursLabel: string,
  coreLesson: string,
  paperEvidence: string,
  kind: TopicKind = "regular",
  contentStatus: TopicContentStatus = "metadata-only",
): ProgramTopic {
  return {
    id,
    title,
    hoursLabel,
    coreLesson,
    paperEvidence,
    kind,
    requirement: kind === "optional" ? "optional" : "required",
    contentStatus,
    skillIds: [],
    prerequisiteTopicIds: [],
  };
}

