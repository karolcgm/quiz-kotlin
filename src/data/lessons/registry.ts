// Konkretne, opublikowane pakiety są wpisane przed szkieletem klasy VI.
// Po dodaniu gotowej lekcji usuwamy więc jej szkielet, aby jeden temat nie
// pojawiał się dwukrotnie w planie i liczniku tematów.
const seenTopicIds = new Set<string>();
const packages: LessonPackage[] = rawPackages.filter((lesson) => {
  if (seenTopicIds.has(lesson.topicId)) return false;
  seenTopicIds.add(lesson.topicId);
  return true;
});

const byId = new Map(packages.map((pkg) => [pkg.id, pkg]));
const byTopicId = new Map<string, LessonPackage>();
for (const pkg of packages) {
  const current = byTopicId.get(pkg.topicId);
  if (!current || pkg.lessonNumber < current.lessonNumber) byTopicId.set(pkg.topicId, pkg);
}

export function listLessonPackages(): LessonPackage[] {
  return packages;
}

export function listPublishedLessonPackages(): LessonPackage[] {
  return packages.filter((pkg) => pkg.status === "published");
}

export function getLessonPackageById(lessonId: string): LessonPackage | undefined {
  return byId.get(lessonId);
}

export function getLessonPackageForTopic(topicId: string): LessonPackage | undefined {
  return byTopicId.get(topicId);
}

export function isTopicLessonPublished(topicId: string): boolean {
  const pkg = byTopicId.get(topicId);
  return pkg?.status === "published";
}
