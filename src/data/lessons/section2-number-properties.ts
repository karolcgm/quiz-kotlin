const SECTION_ID = "M5-S2";

function questions(prefix: string, count: number, generatorId: string): QuestionReference[] {
  return Array.from({ length: count }, (_, index) => ({
    id: `${prefix}-q${index + 1}`,
    generatorId,
    seed: 220_000 + index * 97,
    difficulty: "core",
  }));
}

